-- Run in Supabase SQL Editor or via Supabase Migrations

CREATE TABLE IF NOT EXISTS public.bt_classes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(10) UNIQUE NOT NULL,
  name VARCHAR(100) NOT NULL,
  created_by BIGINT DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.bt_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  class_code VARCHAR(10) DEFAULT NULL REFERENCES public.bt_classes(code) ON UPDATE CASCADE ON DELETE SET NULL,
  streak INT NOT NULL DEFAULT 0,
  last_study_date DATE DEFAULT NULL,
  target_exam_date DATE DEFAULT NULL,
  target_hours INT NOT NULL DEFAULT 500,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_bt_classes_created_by'
  ) THEN
    ALTER TABLE public.bt_classes
      ADD CONSTRAINT fk_bt_classes_created_by
      FOREIGN KEY (created_by) REFERENCES public.bt_users(id) ON DELETE SET NULL;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.bt_study_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.bt_users(id) ON DELETE CASCADE,
  subject VARCHAR(50) NOT NULL,
  seconds INT NOT NULL CHECK (seconds > 0 AND seconds <= 43200),
  session_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_bt_users_class_code ON public.bt_users(class_code);
CREATE INDEX IF NOT EXISTS idx_bt_study_sessions_user_date ON public.bt_study_sessions(user_id, session_date DESC);

CREATE TABLE IF NOT EXISTS public.bt_test_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.bt_users(id) ON DELETE CASCADE,
  subject VARCHAR(50) NOT NULL,
  total INT NOT NULL CHECK (total >= 1),
  wrong INT NOT NULL CHECK (wrong >= 0),
  blank INT NOT NULL DEFAULT 0 CHECK (blank >= 0),
  accuracy NUMERIC(5,2) NOT NULL,
  konkur_score NUMERIC(5,2) DEFAULT NULL,
  note TEXT DEFAULT NULL,
  test_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_bt_test_results_user_created ON public.bt_test_results(user_id, created_at DESC);

ALTER TABLE public.bt_classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bt_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bt_study_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bt_test_results ENABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.bt_classes, public.bt_users, public.bt_study_sessions, public.bt_test_results TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
